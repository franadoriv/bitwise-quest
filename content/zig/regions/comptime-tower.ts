/** A full file: top-level declarations, then `pub fn main` with the body indented. */
const zmain = (top: string, body: string) =>
  `${top}\n\npub fn main() ${/\btry\b/.test(body) ? "!void" : "void"} {\n${body.split("\n").map((l) => "    " + l).join("\n")}\n}`;

/** A no-op log function: hides DebugAllocator's leak log (its addresses change on every run). */
const QUIET =
  'const std = @import("std");\n\npub const std_options: std.Options = .{ .logFn = quiet };\n\nfn quiet(comptime l: std.log.Level, comptime s: @Type(.enum_literal), comptime f: []const u8, a: anytype) void {\n    _ = l;\n    _ = s;\n    _ = f;\n    _ = a;\n}';

