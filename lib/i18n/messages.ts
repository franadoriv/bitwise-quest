export function format(locale: Locale, key: MessageKey, vars?: Vars): string {
  let s: string = MESSAGES[locale][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** The same message in every locale (for text the server hands to the client). */
export function localized(key: MessageKey, vars?: Vars | ((l: Locale) => Vars)): Localized {
  const v = (l: Locale) => (typeof vars === "function" ? vars(l) : vars);
  return Object.fromEntries(LOCALES.map((l) => [l, format(l, key, v(l))])) as Localized;
}
